//! The published Transvoxel tables (`rendering.md` section 2.2).
//!
//! The data below is converted, value for value, from `Transvoxel.cpp`
//! published at transvoxel.org with Eric Lengyel's 2010 dissertation that
//! introduced the algorithm (cited in full in `rendering.md` section 2.2).
//! The original notice:
//!
//! ```text
//! Transvoxel Algorithm Data Tables
//! https://transvoxel.org/
//!
//! Copyright 2009 by Eric Lengyel
//! ```
//!
//! The tables are published under the MIT license. Every structural
//! invariant is checked by the tests at the end of this file, and a few
//! entries are compared against values copied from the published file.
//!
//! Corner numbering of a regular cell: corner `i` sits at `(i & 1, (i >> 1)
//! & 1, (i >> 2) & 1)`. A case index has bit `i` set when corner `i` is
//! inside the matter (the published convention calls these "negative" or
//! solid corners).

/// Triangulation of one regular cell equivalence class.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct RegularCellData {
    /// High nibble: vertex count. Low nibble: triangle count.
    pub geometry_counts: u8,
    /// Groups of three indexes into the case's vertex list, one group per
    /// triangle; unused entries are 0.
    pub vertex_index: [u8; 15],
}

impl RegularCellData {
    /// Number of distinct vertices the class uses.
    pub const fn vertex_count(&self) -> usize {
        (self.geometry_counts >> 4) as usize
    }

    /// Number of triangles the class emits.
    pub const fn triangle_count(&self) -> usize {
        (self.geometry_counts & 0x0F) as usize
    }
}

/// Triangulation of one transition cell equivalence class.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct TransitionCellData {
    /// High nibble: vertex count. Low nibble: triangle count.
    pub geometry_counts: u8,
    /// Groups of three indexes into the case's vertex list, one group per
    /// triangle; unused entries are 0.
    pub vertex_index: [u8; 36],
}

impl TransitionCellData {
    /// Number of distinct vertices the class uses.
    pub const fn vertex_count(&self) -> usize {
        (self.geometry_counts >> 4) as usize
    }

    /// Number of triangles the class emits.
    pub const fn triangle_count(&self) -> usize {
        (self.geometry_counts & 0x0F) as usize
    }
}

/// Pads a published index list with zeros to the table's width.
const fn pad<const W: usize>(v: &[u8]) -> [u8; W] {
    let mut out = [0u8; W];
    let mut i = 0;
    while i < v.len() {
        out[i] = v[i];
        i += 1;
    }
    out
}

/// Pads a published vertex data row with zeros to twelve entries.
const fn row(v: &[u16]) -> [u16; 12] {
    let mut out = [0u16; 12];
    let mut i = 0;
    while i < v.len() {
        out[i] = v[i];
        i += 1;
    }
    out
}

/// Number of entries of row `case` of [`REGULAR_VERTEX_DATA`] that are in
/// use: the vertex count of the case's class.
pub fn regular_vertex_count(case: u8) -> usize {
    REGULAR_CELL_DATA[usize::from(REGULAR_CELL_CLASS[usize::from(case)])].vertex_count()
}

/// The class of transition case `case` (the low seven bits of
/// [`TRANSITION_CELL_CLASS`]) and whether its triangles are inverted (the
/// high bit).
pub fn transition_class(case: u16) -> (usize, bool) {
    let c = TRANSITION_CELL_CLASS[usize::from(case)];
    (usize::from(c & 0x7F), c & 0x80 != 0)
}

